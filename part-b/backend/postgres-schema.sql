-- Supabase roles exist only on hosted instances. Keep our private schema inaccessible to them.
DO $$
BEGIN
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
    REVOKE ALL ON SCHEMA slotbook FROM anon;
    REVOKE ALL ON ALL TABLES IN SCHEMA slotbook FROM anon;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA slotbook FROM anon;
  END IF;
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
    REVOKE ALL ON SCHEMA slotbook FROM authenticated;
    REVOKE ALL ON ALL TABLES IN SCHEMA slotbook FROM authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA slotbook FROM authenticated;
  END IF;
END $$;
