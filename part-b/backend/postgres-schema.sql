-- Private schema: never expose password/session/management data through Supabase's public API.
CREATE SCHEMA IF NOT EXISTS slotbook;
REVOKE ALL ON SCHEMA slotbook FROM PUBLIC;
CREATE TABLE IF NOT EXISTS slotbook.services(id INTEGER PRIMARY KEY,name TEXT NOT NULL,duration INTEGER NOT NULL,price INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.stylists(id INTEGER PRIMARY KEY,name TEXT NOT NULL,days TEXT NOT NULL,start INTEGER NOT NULL,"end" INTEGER NOT NULL,break_start INTEGER NOT NULL,break_end INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.customers(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,mobile TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.admins(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,login_id TEXT NOT NULL UNIQUE,name TEXT NOT NULL,mobile TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.customer_sessions(token_hash TEXT PRIMARY KEY,customer_id INTEGER NOT NULL REFERENCES slotbook.customers(id),expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.admin_sessions(token_hash TEXT PRIMARY KEY,admin_id INTEGER NOT NULL REFERENCES slotbook.admins(id),expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.auth_limits(key TEXT PRIMARY KEY,attempts INTEGER NOT NULL,reset_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS slotbook.bookings(id TEXT PRIMARY KEY,service_id INTEGER NOT NULL REFERENCES slotbook.services(id),stylist_id INTEGER NOT NULL REFERENCES slotbook.stylists(id),date TEXT NOT NULL,start INTEGER NOT NULL,"end" INTEGER NOT NULL,price INTEGER NOT NULL,name TEXT NOT NULL,mobile TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'confirmed' CHECK(status IN ('confirmed','cancelled')),manage_token TEXT NOT NULL,customer_id INTEGER REFERENCES slotbook.customers(id));
CREATE INDEX IF NOT EXISTS booking_day ON slotbook.bookings(date,stylist_id,status);
CREATE INDEX IF NOT EXISTS session_expiry ON slotbook.customer_sessions(expires_at);
CREATE INDEX IF NOT EXISTS admin_session_expiry ON slotbook.admin_sessions(expires_at);
