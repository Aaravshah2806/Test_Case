"""Real database checks. Each test owns a separate, temporary PostgreSQL schema."""

import os
from concurrent.futures import ThreadPoolExecutor
from threading import Barrier
from uuid import uuid4

import pytest
from fastapi.testclient import TestClient
from sqlalchemy import func, select
from sqlalchemy.schema import CreateSchema, DropSchema

from app.database import build_engine, session_factory
from app.main import create_app
from app.models import Base, Booking, Service, Stylist
from app.seed import seed_database

pytestmark = pytest.mark.integration


@pytest.fixture
def database():
    if os.getenv("RUN_POSTGRES_TESTS") != "1":
        pytest.skip("Set RUN_POSTGRES_TESTS=1 and configure DATABASE_URL to test PostgreSQL.")
    engine = build_engine()
    schema = f"salon_test_{uuid4().hex}"
    test_engine = engine.execution_options(schema_translate_map={"salon": schema})
    try:
        with engine.begin() as connection:
            connection.execute(CreateSchema(schema))
        Base.metadata.create_all(test_engine)
        yield session_factory(test_engine)
    finally:
        # Only the schema generated by this fixture is removed; app data is untouched.
        with engine.begin() as connection:
            connection.execute(DropSchema(schema, cascade=True, if_exists=True))
        engine.dispose()


@pytest.fixture
def client(database):
    with TestClient(create_app(database)) as test_client:
        yield test_client


def details(**changes):
    return {
        "service_id": 1, "stylist_id": 1, "date": "2026-11-02",
        "start_time": "10:00", "customer_name": "Asha Shah", "mobile": "0123456789",
        **changes,
    }


def times(client, **changes):
    response = client.get("/api/availability", params={
        "service_id": 1, "stylist_id": 1, "date": "2026-11-02", **changes,
    })
    assert response.status_code == 200
    return response.json()["start_times"]


def test_seed_catalog_is_exact_and_idempotent(client, database):
    seed_database(database)
    assert [(s["name"], s["duration_minutes"], s["price_rupees"])
            for s in client.get("/api/services").json()] == [
        ("Haircut", 30, 400), ("Hair spa", 60, 1200),
        ("Beard trim", 15, 200), ("Facial", 45, 900),
    ]
    with database() as session:
        assert session.scalar(select(func.count()).select_from(Service)) == 4
        meera, karan = session.scalars(select(Stylist).order_by(Stylist.id)).all()
        assert meera.working_days == [0, 1, 2, 3, 4, 5]
        assert str(meera.break_start) == "13:00:00"
        assert karan.working_days == [1, 2, 3, 4, 5, 6]
        assert str(karan.break_end) == "15:30:00"


def test_booking_confirmation_and_persistence_across_app_restart(client, database):
    result = client.post("/api/bookings", json=details())
    assert result.status_code == 201
    booking = result.json()
    assert booking["id"]
    assert (booking["service"], booking["stylist"], booking["price_rupees"]) == (
        "Haircut", "Meera", 400,
    )
    assert booking["starts_at"] == "2026-11-02T10:00:00+05:30"
    assert booking["ends_at"] == "2026-11-02T10:30:00+05:30"
    with TestClient(create_app(database)) as restarted:
        assert "10:00" not in times(restarted)
        assert "10:15" not in times(restarted)
        assert "10:30" in times(restarted)
    with database() as session:
        saved = session.scalar(select(Booking))
        assert saved.mobile == "0123456789"


def test_overlap_is_rejected_but_other_stylist_and_adjacent_time_work(client):
    assert client.post("/api/bookings", json=details()).status_code == 201
    assert client.post("/api/bookings", json=details(start_time="10:15")).status_code == 409
    assert client.post("/api/bookings", json=details(start_time="10:30")).status_code == 201
    other = client.post("/api/bookings", json=details(stylist_id=2, start_time="11:00"))
    assert other.status_code == 201


@pytest.mark.parametrize("change", [
    {"customer_name": "   "}, {"mobile": "123"}, {"mobile": 1234567890},
    {"start_time": "10:01"}, {"date": "not-a-date"}, {"price_rupees": 1},
])
def test_backend_rejects_invalid_direct_requests(client, database, change):
    assert client.post("/api/bookings", json=details(**change)).status_code == 422
    with database() as session:
        assert session.scalar(select(func.count()).select_from(Booking)) == 0


def test_unknown_ids_and_out_of_hours_requests_are_rejected(client):
    assert client.post("/api/bookings", json=details(service_id=999)).status_code == 404
    assert client.post("/api/bookings", json=details(stylist_id=999)).status_code == 404
    assert client.post("/api/bookings", json=details(start_time="09:45")).status_code == 409
    assert client.post("/api/bookings", json=details(start_time="18:45")).status_code == 409


@pytest.mark.parametrize("second_start", ["10:00", "10:15"])
def test_concurrent_same_or_overlapping_slots_cannot_both_succeed(client, database, second_start):
    gate = Barrier(2)

    def book(start):
        gate.wait(timeout=10)
        return client.post("/api/bookings", json=details(start_time=start)).status_code

    with ThreadPoolExecutor(max_workers=2) as executor:
        results = list(executor.map(book, ["10:00", second_start]))
    assert sorted(results) == [201, 409]
    with database() as session:
        assert session.scalar(select(func.count()).select_from(Booking)) == 1
